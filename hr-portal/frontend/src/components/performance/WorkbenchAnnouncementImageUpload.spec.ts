import { flushPromises, mount } from '@vue/test-utils'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import WorkbenchAnnouncementImageUpload from './WorkbenchAnnouncementImageUpload.vue'
const api = vi.hoisted(() => ({ announcementImage: vi.fn(), uploadAnnouncementImage: vi.fn() }))
vi.mock('@/api/performance', () => ({ performanceWorkbenchSettingsApi: api }))
function deferred<T>() { let resolve!: (value: T) => void; let reject!: (error: Error) => void; const promise = new Promise<T>((yes, no) => { resolve = yes; reject = no }); return { promise, resolve, reject } }
function uploader(id: number | null = null) {
  const wrapper = mount(WorkbenchAnnouncementImageUpload, { props: { modelValue: id } })
  wrapper.setProps({ 'onUpdate:modelValue': value => wrapper.setProps({ modelValue: value }) })
  return wrapper
}
async function drop(wrapper: ReturnType<typeof uploader>, files: File[]) { await wrapper.get('.announcement-upload').trigger('drop', { dataTransfer: { files } }); await flushPromises() }
const image = () => new File(['png'], 'picture.png', { type: 'image/png' })

describe('WorkbenchAnnouncementImageUpload', () => {
  beforeEach(() => {
    vi.clearAllMocks()
    Object.defineProperty(URL, 'createObjectURL', { configurable: true, value: vi.fn(() => 'blob:preview') })
    Object.defineProperty(URL, 'revokeObjectURL', { configurable: true, value: vi.fn() })
    api.announcementImage.mockResolvedValue(new Blob(['image'], { type: 'image/png' }))
    api.uploadAnnouncementImage.mockResolvedValue({ id: 20 })
  })
  it('renders the captured full-width Chinese empty upload state and opens the file picker', async () => {
    const wrapper = uploader()
    expect(wrapper.classes()).toContain('is-empty')
    expect(wrapper.get('.announcement-upload__empty').text()).toBe('拖拽文件至此或选择文件上传')
    expect(wrapper.get('.announcement-upload__language').text()).toBe('中文')
    expect(wrapper.find('.announcement-upload__actions').exists()).toBe(false)
    const click = vi.spyOn(wrapper.get('input').element, 'click').mockImplementation(() => undefined)
    await wrapper.get('[aria-label="中文配图上传"]').trigger('click')
    expect(click).toHaveBeenCalledOnce()
  })
  it('loads authenticated blobs without a cycle and releases object URLs on replace and unmount', async () => {
    const wrapper = uploader(5)
    await flushPromises()
    expect(api.announcementImage).toHaveBeenCalledWith(5)
    expect(wrapper.get('img').attributes('src')).toBe('blob:preview')
    await wrapper.setProps({ modelValue: 6 })
    await flushPromises()
    expect(URL.revokeObjectURL).toHaveBeenCalledWith('blob:preview')
    wrapper.unmount()
    expect(URL.revokeObjectURL).toHaveBeenCalledTimes(2)
  })
  it('uploads via drag/drop, replaces, removes, and reloads server image', async () => {
    const wrapper = uploader()
    await drop(wrapper, [image()])
    expect(api.uploadAnnouncementImage).toHaveBeenCalledTimes(1)
    expect(wrapper.emitted('update:modelValue')?.[0]).toEqual([20])
    expect(wrapper.text()).toContain('替换图片')
    await wrapper.get('[aria-label="中文配图移除"]').trigger('click')
    expect(wrapper.emitted('update:modelValue')?.at(-1)).toEqual([null])
    expect(wrapper.find('img').exists()).toBe(false)
  })
  it('rejects unsupported files, oversized files and multiple files', async () => {
    const wrapper = uploader()
    await drop(wrapper, [new File(['x'], 'fake.svg', { type: 'image/svg+xml' })])
    expect(wrapper.text()).toContain('仅支持 JPG、JPEG、PNG 图片')
    const large = image(); Object.defineProperty(large, 'size', { value: 10 * 1024 * 1024 + 1 })
    await drop(wrapper, [large])
    expect(wrapper.text()).toContain('图片不能超过 10 MiB')
    await drop(wrapper, [image(), image()])
    expect(wrapper.text()).toContain('每种语言仅支持一张图片')
    expect(api.uploadAnnouncementImage).not.toHaveBeenCalled()
  })
  it('retains existing image on upload failure and retries the failed file', async () => {
    api.uploadAnnouncementImage.mockRejectedValueOnce(new Error('failed'))
    const wrapper = uploader(5)
    await flushPromises()
    await drop(wrapper, [image()])
    expect(wrapper.props('modelValue')).toBe(5)
    expect(wrapper.text()).toContain('图片上传失败')
    expect(wrapper.emitted('state')?.at(-1)).toEqual([{ busy: false, invalid: true }])
    await wrapper.findAll('button').find(node => node.text() === '重试')!.trigger('click')
    await flushPromises()
    expect(wrapper.props('modelValue')).toBe(20)
  })
  it('offers load and decode failure retry without erasing image id', async () => {
    api.announcementImage.mockRejectedValueOnce(new Error('failed'))
    const wrapper = uploader(5)
    await flushPromises()
    expect(wrapper.text()).toContain('图片加载失败')
    await wrapper.findAll('button').find(node => node.text() === '重试')!.trigger('click')
    await flushPromises()
    await wrapper.get('img').trigger('error')
    expect(wrapper.text()).toContain('图片预览失败')
    expect(wrapper.props('modelValue')).toBe(5)
  })
  it('ignores stale load responses after id changes or unmount', async () => {
    const pending = deferred<Blob>()
    api.announcementImage.mockReturnValueOnce(pending.promise)
    const wrapper = uploader(5)
    await wrapper.setProps({ modelValue: 6 })
    await flushPromises()
    pending.resolve(new Blob(['old']))
    await flushPromises()
    expect(URL.createObjectURL).toHaveBeenCalledTimes(1)
    const late = deferred<Blob>()
    api.announcementImage.mockReturnValueOnce(late.promise)
    await wrapper.setProps({ modelValue: 7 })
    wrapper.unmount()
    late.resolve(new Blob(['late']))
    await flushPromises()
    expect(URL.createObjectURL).toHaveBeenCalledTimes(1)
  })
  it('ignores old upload responses when replaced, removed or unmounted', async () => {
    const first = deferred<{ id: number }>()
    api.uploadAnnouncementImage.mockReturnValueOnce(first.promise)
    const wrapper = uploader()
    await drop(wrapper, [image()])
    expect(wrapper.attributes('aria-busy')).toBe('true')
    await drop(wrapper, [image()])
    first.resolve({ id: 99 })
    await flushPromises()
    expect(wrapper.props('modelValue')).toBe(20)
    const second = deferred<{ id: number }>()
    api.uploadAnnouncementImage.mockReturnValueOnce(second.promise)
    await drop(wrapper, [image()])
    await wrapper.get('[aria-label="中文配图移除"]').trigger('click')
    second.resolve({ id: 100 })
    await flushPromises()
    expect(wrapper.props('modelValue')).toBeNull()
    const third = deferred<{ id: number }>()
    api.uploadAnnouncementImage.mockReturnValueOnce(third.promise)
    await drop(wrapper, [image()])
    wrapper.unmount()
    third.resolve({ id: 101 })
    await flushPromises()
    expect(wrapper.emitted('update:modelValue')?.flat() || []).not.toContain(101)
  })
  it('does not upload dropped files while disabled', async () => {
    const wrapper = uploader()
    await wrapper.setProps({ disabled: true })
    await drop(wrapper, [image()])
    expect(api.uploadAnnouncementImage).not.toHaveBeenCalled()
    expect(wrapper.findAll('button').every(node => node.attributes('disabled') !== undefined)).toBe(true)
  })
})
